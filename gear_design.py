"""
Spur gear pair: engineering sizing in Python + parametric CAD in OpenSCAD
=========================================================================
  1. Sizing: for a motor of P kW at n rpm and a 3:1 reduction, search module,
     pinion teeth and face width for the lightest steel gear pair that passes
     tooth bending (Lewis) and surface contact (Hertz) checks with a safety factor
  2. CAD: the chosen pinion and gear are generated by OpenSCAD from the command
     line (gear.scad, true involute profile) as STL solids and SVG profiles
  3. Verification of the CAD: tip and root radius, tooth thickness on the pitch
     circle and volume, measured on the exported geometry vs gear theory
  4. Figures: design space, 3D render of the pair, and an animation of the
     two gears meshing

Units: mm, N, MPa, s.  Requires OpenSCAD on the PATH (sudo apt install openscad).
"""
import os
import re
import math
import subprocess
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib import animation, cm, colors
from mpl_toolkits.mplot3d.art3d import Poly3DCollection

# ============================ SETTINGS ============================
OPENSCAD = "openscad"
POWER = 5.0e3          # motor power [W]
N1 = 1450.0            # pinion speed [rpm]
RATIO = 3.0            # gear ratio u = z2 / z1
PA = 20.0              # pressure angle [deg]
RHO = 7.85e-9          # steel density [t/mm^3]
SIGMA_F_ALLOW = 200.0  # allowable tooth root bending stress [MPa] (through-hardened steel, illustrative)
SIGMA_H_ALLOW = 900.0  # allowable contact stress [MPa] (through-hardened steel, illustrative)
SF_MIN = 1.5           # required safety factor on both stresses
MODULES = [1.5, 2.0, 2.5, 3.0, 4.0]
Z1_RANGE = range(18, 31)          # >= 18 teeth: no undercut at 20 deg
FACE_FACTORS = [8, 10, 12]        # face width b = k * m (usual range 8 to 16)
OUT = "results"
# ==================================================================

os.makedirs(OUT, exist_ok=True)
os.makedirs("cad", exist_ok=True)

# Lewis form factor Y, 20 deg full-depth teeth (Shigley, Table 14-2)
LEWIS = {12: .245, 13: .261, 14: .277, 15: .290, 16: .296, 17: .303, 18: .309, 19: .314, 20: .322,
         21: .328, 22: .331, 24: .337, 26: .346, 28: .353, 30: .359, 34: .371, 38: .384, 43: .397,
         50: .409, 60: .422, 75: .435, 100: .447, 150: .460, 300: .472, 400: .480}
Z_E = 189.8                       # elastic coefficient steel/steel [sqrt(MPa)]
Z_H = 2.495                       # zone factor, 20 deg spur gears


def lewis_y(z):
    keys = sorted(LEWIS)
    return float(np.interp(z, keys, [LEWIS[k] for k in keys]))


# ------------------------------------------------------------------
# 1. SIZING
# ------------------------------------------------------------------
def check(m, z1, k):
    z2 = int(round(RATIO * z1))
    b = k * m
    d1, d2 = m * z1, m * z2
    torque = POWER / (2 * math.pi * N1 / 60) * 1e3          # N.mm
    ft = 2 * torque / d1                                      # tangential force [N]
    v = math.pi * d1 * N1 / 60e3                              # pitch line speed [m/s]
    kv = (6.1 + v) / 6.1                                      # Barth velocity factor (cut teeth)
    u = z2 / z1
    sig_f = kv * ft / (b * m * lewis_y(z1))                   # Lewis bending, pinion (weaker tooth)
    sig_h = Z_E * Z_H * math.sqrt(kv * ft * (u + 1) / (b * d1 * u))   # Hertz contact
    bore1, bore2 = 0.25 * d1, 0.25 * d2
    mass = RHO * b * math.pi / 4 * (d1 ** 2 - bore1 ** 2 + d2 ** 2 - bore2 ** 2) * 1e3   # kg, pitch-circle disc
    # transverse contact ratio
    alpha = math.radians(PA)
    ra1, ra2 = d1 / 2 + m, d2 / 2 + m
    rb1, rb2 = d1 / 2 * math.cos(alpha), d2 / 2 * math.cos(alpha)
    a = (d1 + d2) / 2
    eps = (math.sqrt(ra1 ** 2 - rb1 ** 2) + math.sqrt(ra2 ** 2 - rb2 ** 2) - a * math.sin(alpha)) / (
        math.pi * m * math.cos(alpha))
    sf_f, sf_h = SIGMA_F_ALLOW / sig_f, SIGMA_H_ALLOW / sig_h
    return dict(m=m, z1=z1, z2=z2, k=k, b=b, d1=d1, d2=d2, a=a, ft=ft, v=v, kv=kv, torque=torque,
                sig_f=sig_f, sig_h=sig_h, sf_f=sf_f, sf_h=sf_h, mass=mass, eps=eps, bore1=bore1, bore2=bore2,
                ok=min(sf_f, sf_h) >= SF_MIN)


# ------------------------------------------------------------------
# 2. CAD (OpenSCAD command line)
# ------------------------------------------------------------------
def scad(out, m, z, b, bore, mode):
    args = [OPENSCAD, "-o", out, "-D", f"m={m}", "-D", f"z={z}", "-D", f"b={b}", "-D", f"bore={bore}",
            "-D", f"pa={PA}", "-D", f"mode={mode}", "gear.scad"]
    res = subprocess.run(args, capture_output=True, text=True)
    if res.returncode != 0 or not os.path.exists(out):
        raise RuntimeError(res.stderr[-1500:])


def read_svg(path):
    """Closed contours of an OpenSCAD SVG (y axis flipped back to math convention)."""
    with open(path) as f:
        txt = f.read()
    contours = []
    for chunk in re.findall(r"M ([^z]+) z", txt):
        pts = np.array([[float(a), -float(b)] for a, b in re.findall(r"(-?[\d.e+-]+),(-?[\d.e+-]+)", chunk)])
        contours.append(pts)
    return contours


def read_stl(path):
    """Triangles of an ASCII STL."""
    with open(path) as f:
        v = np.array(re.findall(r"vertex\s+(\S+)\s+(\S+)\s+(\S+)", f.read()), dtype=float)
    return v.reshape(-1, 3, 3)


def stl_volume(tris):
    """Divergence theorem: sum of signed tetrahedra volumes."""
    return abs(np.einsum("ij,ij->i", tris[:, 0], np.cross(tris[:, 1], tris[:, 2])).sum()) / 6


def polygon_area(p):
    x, y = p[:, 0], p[:, 1]
    return 0.5 * abs(np.dot(x, np.roll(y, 1)) - np.dot(y, np.roll(x, 1)))


def tooth_thickness_at(p, r, z):
    """Mean arc thickness of the teeth where the outer profile crosses the circle of radius r."""
    rad = np.hypot(p[:, 0], p[:, 1])
    ang = np.arctan2(p[:, 1], p[:, 0])
    cross = []
    for i in range(len(p)):
        j = (i + 1) % len(p)
        if (rad[i] - r) * (rad[j] - r) < 0:
            t = (r - rad[i]) / (rad[j] - rad[i])
            da = math.atan2(math.sin(ang[j] - ang[i]), math.cos(ang[j] - ang[i]))
            cross.append((ang[i] + t * da, rad[j] > rad[i]))       # (angle, going outwards?)
    cross.sort()
    widths = []
    for (a0, up0), (a1, up1) in zip(cross, cross[1:] + [(cross[0][0] + 2 * math.pi, cross[0][1])]):
        if up0 and not up1:                                         # inside a tooth
            widths.append(a1 - a0)
    return r * np.mean(widths), len(widths)


# ------------------------------------------------------------------
# PLOT HELPERS
# ------------------------------------------------------------------
def draw_stl(ax, tris, offset, color):
    light = np.array([0.3, -0.5, 0.8]) / np.linalg.norm([0.3, -0.5, 0.8])
    n = np.cross(tris[:, 1] - tris[:, 0], tris[:, 2] - tris[:, 0])
    n = n / (np.linalg.norm(n, axis=1)[:, None] + 1e-12)
    shade = 0.35 + 0.65 * np.abs(n @ light)
    base = np.array(colors.to_rgb(color))
    ax.add_collection3d(Poly3DCollection(tris + offset, facecolors=base * shade[:, None], edgecolors="none"))


def rot(p, ang, center=(0, 0)):
    c, s = math.cos(ang), math.sin(ang)
    return p @ np.array([[c, s], [-s, c]]) + np.array(center)


# ==================================================================
def main():
    report = []

    def log(text=""):
        print(text)
        report.append(text)

    # ---------------- Sizing search ----------------
    cands = [check(m, z1, k) for m in MODULES for z1 in Z1_RANGE for k in FACE_FACTORS]
    feas = [c for c in cands if c["ok"]]
    best = min(feas, key=lambda c: c["mass"])
    log("SPUR GEAR PAIR: Python sizing + OpenSCAD CAD")
    log(f"Motor {POWER / 1e3:.1f} kW at {N1:.0f} rpm, ratio {RATIO:.0f}:1, steel, pressure angle {PA:.0f} deg")
    log(f"Allowables: bending {SIGMA_F_ALLOW:.0f} MPa, contact {SIGMA_H_ALLOW:.0f} MPa, required SF {SF_MIN}")
    log(f"{len(cands)} candidate pairs checked, {len(feas)} pass both checks\n")
    log("LIGHTEST PAIR THAT PASSES")
    log(f"  module {best['m']} mm, pinion {best['z1']} teeth, gear {best['z2']} teeth, face width {best['b']:.1f} mm")
    log(f"  pitch diameters {best['d1']:.1f} / {best['d2']:.1f} mm, centre distance {best['a']:.1f} mm")
    log(f"  pinion torque {best['torque'] / 1e3:.1f} N.m, tangential force {best['ft']:.0f} N, "
        f"pitch line speed {best['v']:.2f} m/s, Kv = {best['kv']:.2f}")
    log(f"  bending stress {best['sig_f']:.1f} MPa (SF {best['sf_f']:.2f}), "
        f"contact stress {best['sig_h']:.0f} MPa (SF {best['sf_h']:.2f})")
    log(f"  contact ratio {best['eps']:.2f} (above 1.2: always more than one tooth pair in mesh, smooth running)")
    log(f"  mass of the pair {best['mass']:.2f} kg")
    gov = "contact (pitting)" if best["sf_h"] < best["sf_f"] else "bending"
    log(f"  governing failure mode: {gov}")

    # ---------------- CAD with OpenSCAD ----------------
    m, b = best["m"], best["b"]
    parts = {"pinion": (best["z1"], best["bore1"]), "gear": (best["z2"], best["bore2"])}
    geo = {}
    for name, (z, bore) in parts.items():
        scad(f"cad/{name}.stl", m, z, b, round(bore, 1), 3)
        scad(f"cad/{name}.svg", m, z, b, round(bore, 1), 2)
        cont = read_svg(f"cad/{name}.svg")
        outer = max(cont, key=polygon_area)
        tris = read_stl(f"cad/{name}.stl")
        rp = m * z / 2
        rad = np.hypot(outer[:, 0], outer[:, 1])
        s, nteeth = tooth_thickness_at(outer, rp, z)
        area = polygon_area(outer) - math.pi * round(bore, 1) ** 2 / 4
        geo[name] = dict(z=z, outer=outer, tris=tris, rp=rp, ra=rad.max(), rf=rad.min(), s=s, nteeth=nteeth,
                         vol_stl=stl_volume(tris), vol_svg=area * b)

    log("\nCAD VERIFICATION (geometry measured on the OpenSCAD output vs gear theory)")
    log(f"{'':8} {'teeth':>6} {'tip r':>15} {'root r':>15} {'thickness at pitch':>22} {'volume STL vs SVG':>20}")
    for name, g in geo.items():
        log(f"{name:8} {g['nteeth']:>6} {g['ra']:7.3f}/{g['rp'] + m:<7.3f} {g['rf']:7.3f}/{g['rp'] - 1.25 * m:<7.3f} "
            f"{g['s']:9.4f}/{math.pi * m / 2:<9.4f} {(g['vol_stl'] / g['vol_svg'] - 1) * 100:+19.3f}%")
    log("  (each pair: measured / theory; tooth thickness on the pitch circle = pi m / 2 with zero backlash)")

    # ================= FIGURES =================
    # 1. Design space
    fig, ax = plt.subplots(figsize=(9, 5.5))
    mk = dict(zip(FACE_FACTORS, ["o", "s", "^"]))
    norm = colors.Normalize(min(MODULES), max(MODULES))
    for c in cands:
        ax.scatter(c["mass"], min(c["sf_f"], c["sf_h"]), marker=mk[c["k"]], s=22, color=cm.viridis(norm(c["m"])),
                   alpha=0.9 if c["ok"] else 0.35)
    ax.scatter(best["mass"], min(best["sf_f"], best["sf_h"]), s=300, facecolors="none", edgecolors="tab:red", lw=2)
    ax.annotate(f"chosen: m = {best['m']}, z1 = {best['z1']}, b = {best['b']:.0f} mm",
                (best["mass"], min(best["sf_f"], best["sf_h"])), textcoords="offset points", xytext=(10, 12),
                color="tab:red", fontsize=9)
    ax.axhline(SF_MIN, color="tab:red", ls="--", lw=1)
    for k, mm in mk.items():
        ax.scatter([], [], marker=mm, color="gray", label=f"b = {k} m")
    fig.colorbar(cm.ScalarMappable(norm=norm, cmap=cm.viridis), ax=ax, label="module m [mm]")
    ax.set_xlabel("Mass of the gear pair [kg]")
    ax.set_ylabel("Lowest safety factor (bending or contact)")
    ax.set_title(f"{len(cands)} gear pairs: lightest above the dashed line wins")
    ax.set_yscale("log")
    ax.grid(alpha=0.3, which="both")
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(f"{OUT}/design_space.png", dpi=150)
    plt.close(fig)

    # 2. Bending vs contact for the chosen module
    fig, ax = plt.subplots(figsize=(8, 4.5))
    for k, ls in zip(FACE_FACTORS, ["-", "--", ":"]):
        rows = [c for c in cands if c["m"] == best["m"] and c["k"] == k]
        ax.plot([c["z1"] for c in rows], [c["sf_f"] for c in rows], ls, color="tab:blue", label=f"bending, b = {k} m")
        ax.plot([c["z1"] for c in rows], [c["sf_h"] for c in rows], ls, color="tab:orange", label=f"contact, b = {k} m")
    ax.axhline(SF_MIN, color="tab:red", lw=1)
    ax.set_xlabel("Pinion teeth z1")
    ax.set_ylabel("Safety factor")
    ax.set_title(f"Module {best['m']} mm: more teeth = bigger gears = lower stresses")
    ax.grid(alpha=0.3)
    ax.legend(fontsize=7, ncol=2)
    fig.tight_layout()
    fig.savefig(f"{OUT}/bending_vs_contact.png", dpi=150)
    plt.close(fig)

    # 3. 3D render of the pair
    fig = plt.figure(figsize=(10, 6))
    ax = fig.add_subplot(projection="3d")
    a = best["a"]
    draw_stl(ax, geo["pinion"]["tris"], np.array([0, 0, 0]), "#c0c6cc")
    draw_stl(ax, geo["gear"]["tris"], np.array([a, 0, 0]), "#d9a35b")
    r2 = geo["gear"]["ra"]
    ax.set_xlim(-geo["pinion"]["ra"] - 5, a + r2 + 5)
    ax.set_ylim(-r2 - 5, r2 + 5)
    ax.set_zlim(-30, b + 30)
    ax.set_box_aspect((a + r2 + geo["pinion"]["ra"] + 10, 2 * r2 + 10, b + 60))
    ax.view_init(elev=35, azim=-60)
    ax.set_axis_off()
    ax.set_title(f"OpenSCAD STL output: pinion z = {best['z1']} and gear z = {best['z2']}, m = {m} mm", fontsize=11)
    fig.tight_layout()
    fig.savefig(f"{OUT}/gear_pair_3d.png", dpi=140)
    plt.close(fig)

    # 4. Meshing animation (2D profiles from the SVG export)
    z1, z2 = best["z1"], best["z2"]
    p1, p2 = geo["pinion"]["outer"], geo["gear"]["outer"]
    pitch2 = 2 * math.pi / z2
    offset2 = math.pi + pitch2 / 2 - (math.pi % pitch2)        # puts a tooth space of the gear facing the pinion
    fig, ax = plt.subplots(figsize=(9, 5))
    frames = 48
    step = 2 * math.pi / z1 / 12

    def frame(i):
        ax.cla()
        phi = i * step
        g1 = rot(p1, phi)
        g2 = rot(p2, -phi / RATIO + offset2, (a, 0))
        ax.fill(g1[:, 0], g1[:, 1], color="#8f9aa5", ec="k", lw=0.5)
        ax.fill(g2[:, 0], g2[:, 1], color="#d9a35b", ec="k", lw=0.5)
        for cx, r in ((0, best["d1"] / 2), (a, best["d2"] / 2)):
            ax.add_patch(plt.Circle((cx, 0), r, fill=False, ls="--", lw=0.6, color="k"))
        ax.plot(*rot(np.array([[0, 0], [best["d1"] / 2 * 0.8, 0]]), phi).T, color="tab:red", lw=2)
        ax.set_aspect("equal")
        ax.set_xlim(-best["d1"] / 2 - 2 * m, a + best["d2"] / 2 + 2 * m)
        ax.set_ylim(-best["d2"] / 2 * 0.75, best["d2"] / 2 * 0.75)
        ax.set_axis_off()
        ax.set_title(f"Pinion {z1} teeth driving gear {z2} teeth (ratio {RATIO:.0f}:1), dashed: pitch circles",
                     fontsize=10)
        return []

    anim = animation.FuncAnimation(fig, frame, frames=frames)
    anim.save(f"{OUT}/meshing.gif", writer=animation.PillowWriter(fps=16))
    plt.close(fig)

    for name in parts:
        os.replace(f"cad/{name}.stl", f"{OUT}/{name}.stl")

    with open(f"{OUT}/report.txt", "w", encoding="utf-8") as f:
        f.write("\n".join(report))
    print(f"\nFigures, STL files and report saved in '{OUT}'.")


if __name__ == "__main__":
    main()
